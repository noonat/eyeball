// Command apitypes writes web/src/api/types.ts from the Go structs the surface's
// API sends, which are in internal/view.
//
// It reads the package's source with go/types and the standard library's source
// importer, so it needs nothing outside the standard library. go/types sees
// constants where reflection cannot, which is what lets a named string type
// with constants become a union of its values.
//
// A Go kind with no exact TypeScript form is an error that names the field.
// Guessing would send a field the app trusts as a number through a double that
// cannot hold it. With --check the command writes nothing and fails when the
// committed file differs from what it would write.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/ast"
	"go/constant"
	"go/importer"
	"go/parser"
	"go/token"
	"go/types"
	"os"
	"path/filepath"
	"reflect"
	"regexp"
	"sort"
	"strings"

	"github.com/cockroachdb/errors"
)

// sourceDir and outFile are relative to the repository root.
const (
	sourceDir = "internal/view"
	outFile   = "web/src/api/types.ts"
)

func main() {
	if err := run(os.Args[1:]); err != nil {
		fmt.Fprintf(os.Stderr, "apitypes: %v\n", err)
		os.Exit(1)
	}
}

// run writes the file, or checks it, as its arguments say.
func run(args []string) error {
	check := len(args) == 1 && args[0] == "--check"
	if len(args) > 0 && !check {
		return errors.Newf("usage: apitypes [--check], got %q", strings.Join(args, " "))
	}
	root, err := repoRoot()
	if err != nil {
		return err
	}
	want, err := Generate(filepath.Join(root, sourceDir))
	if err != nil {
		return err
	}
	path := filepath.Join(root, outFile)
	if !check {
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			return errors.WithStack(err)
		}
		return errors.WithStack(os.WriteFile(path, want, 0o644))
	}
	have, err := os.ReadFile(path)
	if err != nil && !os.IsNotExist(err) {
		return errors.WithStack(err)
	}
	if !bytes.Equal(have, want) {
		return errors.Newf("%s is stale. Run: make api", outFile)
	}
	return nil
}

// Generate returns the TypeScript for the exported types of the package in dir.
func Generate(dir string) ([]byte, error) {
	fset := token.NewFileSet()
	files, err := parseDir(fset, dir)
	if err != nil {
		return nil, err
	}
	var typeErrs []error
	conf := types.Config{
		Importer: importer.ForCompiler(fset, "source", nil),
		Error:    func(err error) { typeErrs = append(typeErrs, err) },
	}
	pkg, _ := conf.Check("view", fset, files, nil)
	if len(typeErrs) > 0 {
		return nil, errors.Wrapf(typeErrs[0], "type-check %s", dir)
	}
	g := &gen{pkg: pkg, docs: collectDocs(files), seen: map[*types.Named]bool{}}
	var decls []string
	for _, name := range pkg.Scope().Names() {
		tn, ok := pkg.Scope().Lookup(name).(*types.TypeName)
		if !ok || !tn.Exported() {
			continue
		}
		decl, err := g.declare(tn)
		if err != nil {
			return nil, err
		}
		decls = append(decls, decl)
	}
	var out bytes.Buffer
	out.WriteString("// Code generated by tool/apitypes from " + sourceDir + ". DO NOT EDIT.\n\n")
	out.WriteString(strings.Join(decls, "\n"))
	return out.Bytes(), nil
}

// parseDir parses the non-test Go files of one package.
func parseDir(fset *token.FileSet, dir string) ([]*ast.File, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, errors.WithStack(err)
	}
	var files []*ast.File
	for _, e := range entries {
		name := e.Name()
		if e.IsDir() || !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") {
			continue
		}
		f, err := parser.ParseFile(fset, filepath.Join(dir, name), nil, parser.ParseComments)
		if err != nil {
			return nil, errors.WithStack(err)
		}
		files = append(files, f)
	}
	if len(files) == 0 {
		return nil, errors.Newf("no Go files in %s", dir)
	}
	return files, nil
}

// docs holds the comments that go with a type and with each of its fields.
type docs struct {
	types  map[string]string
	fields map[string]string
}

// collectDocs reads every type's doc comment and every field's, keyed by the
// type's name and by "Type.Field".
func collectDocs(files []*ast.File) docs {
	d := docs{types: map[string]string{}, fields: map[string]string{}}
	for _, f := range files {
		for _, decl := range f.Decls {
			gd, ok := decl.(*ast.GenDecl)
			if !ok || gd.Tok != token.TYPE {
				continue
			}
			for _, spec := range gd.Specs {
				ts := spec.(*ast.TypeSpec)
				doc := ts.Doc
				if doc == nil && len(gd.Specs) == 1 {
					doc = gd.Doc
				}
				if doc != nil {
					d.types[ts.Name.Name] = strings.TrimSpace(doc.Text())
				}
				st, ok := ts.Type.(*ast.StructType)
				if !ok {
					continue
				}
				for _, field := range st.Fields.List {
					if field.Doc == nil {
						continue
					}
					for _, n := range field.Names {
						d.fields[ts.Name.Name+"."+n.Name] = strings.TrimSpace(field.Doc.Text())
					}
				}
			}
		}
	}
	return d
}

// gen writes the declarations of one package.
type gen struct {
	pkg  *types.Package
	docs docs
	// seen is the named types already checked, which also ends the walk of a
	// type that refers to itself.
	seen map[*types.Named]bool
}

// declare is the TypeScript declaration of one exported type.
func (g *gen) declare(tn *types.TypeName) (string, error) {
	name := tn.Name()
	var b strings.Builder
	writeDoc(&b, g.docs.types[name], "")
	switch u := tn.Type().Underlying().(type) {
	case *types.Struct:
		fields, err := g.fields(name, u)
		if err != nil {
			return "", err
		}
		if len(fields) == 0 {
			b.WriteString("export interface " + name + " {}\n")
			break
		}
		b.WriteString("export interface " + name + " {\n")
		for _, f := range fields {
			writeDoc(&b, f.doc, "  ")
			b.WriteString("  " + f.line + "\n")
		}
		b.WriteString("}\n")
	case *types.Basic:
		if u.Kind() == types.String {
			if values := g.constants(tn); len(values) > 0 {
				b.WriteString(union(name, values))
				break
			}
		}
		base, _, err := g.expr(u, name)
		if err != nil {
			return "", err
		}
		b.WriteString("export type " + name + " = " + base + ";\n")
	default:
		base, null, err := g.expr(u, name)
		if err != nil {
			return "", err
		}
		if null {
			base += " | null"
		}
		b.WriteString("export type " + name + " = " + base + ";\n")
	}
	return b.String(), nil
}

// field is one property of an interface.
type field struct {
	doc, line string
}

// fields maps a struct's exported fields as encoding/json names them.
func (g *gen) fields(owner string, st *types.Struct) ([]field, error) {
	var out []field
	for i := range st.NumFields() {
		f := st.Field(i)
		where := owner + "." + f.Name()
		if f.Embedded() {
			return nil, errors.Newf("%s: an embedded field has no exact form here, name it", where)
		}
		if !f.Exported() {
			continue
		}
		tag := reflect.StructTag(st.Tag(i)).Get("json")
		if tag == "-" {
			continue
		}
		name, opts, _ := strings.Cut(tag, ",")
		if name == "" {
			name = f.Name()
		}
		optional, quoted := false, false
		for _, o := range strings.Split(opts, ",") {
			switch o {
			case "omitempty", "omitzero":
				optional = true
			case "string":
				quoted = true
			}
		}
		var base string
		var null bool
		var err error
		if quoted {
			base, err = quotedType(f.Type())
			if err != nil {
				return nil, errors.Wrap(err, where)
			}
		} else if base, null, err = g.expr(f.Type(), where); err != nil {
			return nil, err
		}
		if null {
			base += " | null"
		}
		mark := ""
		if optional {
			mark = "?"
		}
		out = append(out, field{doc: g.docs.fields[where], line: propName(name) + mark + ": " + base + ";"})
	}
	return out, nil
}

// quotedType is the type of a field carrying the ",string" option, which
// encoding/json applies to strings, numbers and booleans and writes as a quoted
// string. Only those fields, and only directly, are quoted.
func quotedType(t types.Type) (string, error) {
	b, ok := types.Unalias(t).Underlying().(*types.Basic)
	if !ok || b.Kind() == types.String || b.Info()&(types.IsNumeric|types.IsBoolean) == 0 {
		return "", errors.Newf("the \",string\" option applies to a number or a boolean, not %s", t)
	}
	if _, isPtr := t.(*types.Pointer); isPtr {
		return "", errors.New("the \",string\" option on a pointer is not mapped")
	}
	return "string", nil
}

// expr maps a type to its TypeScript form, and says whether Go sends null for
// it: a nil slice, a nil map and a nil pointer all are.
func (g *gen) expr(t types.Type, where string) (string, bool, error) {
	t = types.Unalias(t)
	switch t := t.(type) {
	case *types.Basic:
		return basic(t, where)
	case *types.Named:
		obj := t.Obj()
		if obj.Pkg() != nil && obj.Pkg().Path() == "time" && obj.Name() == "Time" {
			return "string", false, nil
		}
		if obj.Pkg() != g.pkg {
			return "", false, errors.Newf("%s: %s is from another package and has no mapping", where, t)
		}
		if !obj.Exported() {
			return "", false, errors.Newf("%s: %s is not exported, so the file would not declare it", where, obj.Name())
		}
		if _, err := g.checkNamed(t, where); err != nil {
			return "", false, err
		}
		return obj.Name(), false, nil
	case *types.Pointer:
		base, _, err := g.expr(t.Elem(), where)
		return base, true, err
	case *types.Slice:
		if b, ok := t.Elem().Underlying().(*types.Basic); ok && b.Kind() == types.Uint8 {
			return "string", true, nil
		}
		elem, null, err := g.expr(t.Elem(), where)
		if err != nil {
			return "", false, err
		}
		return list(elem, null), true, nil
	case *types.Map:
		key, ok := t.Key().Underlying().(*types.Basic)
		if !ok || key.Kind() != types.String {
			return "", false, errors.Newf("%s: a map keyed by %s has no exact form, JSON keys are strings", where, t.Key())
		}
		elem, null, err := g.expr(t.Elem(), where)
		if err != nil {
			return "", false, err
		}
		if null {
			elem += " | null"
		}
		return "Record<string, " + elem + ">", true, nil
	case *types.Interface:
		return "", false, errors.Newf("%s: an interface has no exact form", where)
	case *types.Struct:
		return "", false, errors.Newf("%s: an anonymous struct is not mapped, name it", where)
	case *types.Array:
		return "", false, errors.Newf("%s: an array is not mapped, use a slice", where)
	}
	return "", false, errors.Newf("%s: %s has no exact form", where, t)
}

// checkNamed makes sure a named type used in a field is itself mappable, so a
// planted fault inside it is reported rather than passed over.
func (g *gen) checkNamed(t *types.Named, where string) (string, error) {
	if g.seen[t] {
		return "", nil
	}
	g.seen[t] = true
	switch u := t.Underlying().(type) {
	case *types.Struct:
		_, err := g.fields(t.Obj().Name(), u)
		return "", err
	default:
		_, _, err := g.expr(u, t.Obj().Name())
		return "", err
	}
}

// basic maps a Go basic type. An integer that can pass 2^53 has no exact form,
// because a JSON number is read as a double.
func basic(b *types.Basic, where string) (string, bool, error) {
	switch b.Kind() {
	case types.Bool:
		return "boolean", false, nil
	case types.String:
		return "string", false, nil
	case types.Int8, types.Int16, types.Int32, types.Uint8, types.Uint16, types.Uint32, types.Float32, types.Float64:
		return "number", false, nil
	case types.Int, types.Int64, types.Uint, types.Uint64, types.Uintptr:
		return "", false, errors.Newf("%s: %s can pass 2^53, which a JSON number cannot hold. Use int32, or send it as a string with the \",string\" option", where, b)
	}
	return "", false, errors.Newf("%s: %s has no exact form", where, b)
}

// list is an array type of elem, in parentheses where elem has a union.
func list(elem string, null bool) string {
	if null {
		return "(" + elem + " | null)[]"
	}
	return elem + "[]"
}

// constants is the values of the exported constants declared with type tn, in
// order of value.
func (g *gen) constants(tn *types.TypeName) []string {
	var out []string
	for _, name := range g.pkg.Scope().Names() {
		c, ok := g.pkg.Scope().Lookup(name).(*types.Const)
		if !ok || !types.Identical(c.Type(), tn.Type()) || c.Val().Kind() != constant.String {
			continue
		}
		out = append(out, constant.StringVal(c.Val()))
	}
	sort.Strings(out)
	return out
}

// union writes a string union, on one line where it fits in 80 columns and one
// member to a line where it does not, which is how oxfmt lays it out.
func union(name string, values []string) string {
	quoted := make([]string, len(values))
	for i, v := range values {
		quoted[i] = quote(v)
	}
	one := "export type " + name + " = " + strings.Join(quoted, " | ") + ";\n"
	if len(one) <= 81 {
		return one
	}
	return "export type " + name + " =\n  | " + strings.Join(quoted, "\n  | ") + ";\n"
}

// quote writes a string as a TypeScript literal. JSON's escapes are valid
// there, and unlike a Go literal's they never name a byte.
func quote(s string) string {
	var b bytes.Buffer
	enc := json.NewEncoder(&b)
	enc.SetEscapeHTML(false)
	_ = enc.Encode(s)
	return strings.TrimSuffix(b.String(), "\n")
}

var identifier = regexp.MustCompile(`^[A-Za-z_$][A-Za-z0-9_$]*$`)

// propName writes a property name, quoted where it is not an identifier.
func propName(name string) string {
	if identifier.MatchString(name) {
		return name
	}
	return quote(name)
}

// writeDoc writes a Go doc comment as a block comment, indented.
func writeDoc(b *strings.Builder, doc, indent string) {
	if doc == "" {
		return
	}
	b.WriteString(indent + "/**\n")
	for _, line := range strings.Split(doc, "\n") {
		line = strings.TrimRight(line, " ")
		if line == "" {
			b.WriteString(indent + " *\n")
			continue
		}
		b.WriteString(indent + " * " + strings.ReplaceAll(line, "*/", "* /") + "\n")
	}
	b.WriteString(indent + " */\n")
}

// repoRoot is the nearest directory above the working directory holding a go.mod.
func repoRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", errors.WithStack(err)
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", errors.New("no go.mod above the working directory")
		}
		dir = parent
	}
}
